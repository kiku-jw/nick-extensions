export type MessageKey = keyof typeof EN_MESSAGES;

function fallbackFormat(message: string, substitutions: string | string[] | undefined): string {
  const values = substitutions === undefined
    ? []
    : Array.isArray(substitutions) ? substitutions : [substitutions];
  return values.reduce((result, value, index) => result.replaceAll(`$${index + 1}`, value), message);
}

export function t(key: MessageKey, substitutions?: string | string[]): string {
  try {
    if (typeof chrome !== 'undefined' && chrome.i18n?.getMessage) {
      const translated = chrome.i18n.getMessage(key, substitutions);
      if (translated) return translated;
    }
  } catch {
    // Unit tests and partially initialized extension contexts use English fallbacks.
  }
  return fallbackFormat(EN_MESSAGES[key], substitutions);
}

export function featureNameKey(id: string): MessageKey {
  return `feature_${id}_name` as MessageKey;
}

export function featureBlurbKey(id: string): MessageKey {
  return `feature_${id}_blurb` as MessageKey;
}

export function uiLanguage(): 'ru' | 'en' {
  try {
    const locale = chrome.i18n?.getUILanguage?.() || '';
    return /^ru(?:-|$)/i.test(locale) ? 'ru' : 'en';
  } catch {
    return 'en';
  }
}

export function localizeDocument(root: ParentNode = document): void {
  if (root === document) {
    document.documentElement.lang = uiLanguage();
    document.title = t('extension_name');
  }
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n as MessageKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((element) => {
    element.title = t(element.dataset.i18nTitle as MessageKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel as MessageKey));
  });
  root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder as MessageKey);
  });
}
